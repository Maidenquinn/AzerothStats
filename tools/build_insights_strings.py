"""Generate the additive insights catalog; --check makes CI reject stale output."""

from pathlib import Path
import argparse, json

p = argparse.ArgumentParser()
p.add_argument("--check", action="store_true")
args = p.parse_args()
root = Path(__file__).resolve().parent.parent
catalog = {}
for line in (
    (root / "locales-insights.txt").read_text(encoding="utf-8-sig").splitlines()
):
    if line.strip():
        lg, value = line.split("=", 1)
        catalog[lg] = value.split("|")
assert set(catalog) == set("en fr pl cs de pt es ro tr ru uk zh ja ko".split())
keys = catalog["en"]
assert len(set(keys)) == len(keys)
lines = [
    "-- Generated by tools/build_insights_strings.py from locales-insights.txt.",
    "local A=AzerothStats",
]
for lg, values in catalog.items():
    assert len(values) == len(keys), (lg, len(values), len(keys))
    for key, value in zip(keys, values):
        lines.append(
            "A.uiText."
            + lg
            + "["
            + json.dumps(key, ensure_ascii=False)
            + "]="
            + json.dumps(value, ensure_ascii=False)
        )
text = "\n".join(lines) + "\n"
out = root / "AzerothStats/InsightsStrings.lua"
if args.check:
    assert (
        out.read_text(encoding="utf-8") == text
    ), "Insights catalog is stale; regenerate it"
else:
    out.write_text(text, encoding="utf-8")
print(len(keys), "insights labels in", len(catalog), "languages")
