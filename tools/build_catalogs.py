"""Compile reviewed JSON catalogs to literal-only Lua 5.0 data modules.

No game executable, network access or Lua evaluation is used. --check verifies
that committed output is reproducible from the human-readable source catalogs.
"""

from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parent.parent
MODULES = {
    "Strings.lua": ("uiText",),
    "GameText.lua": ("gameText",),
    "Collection.lua": ("collectionAliases", "collectionSources", "abilityClasses"),
    "Icons.lua": ("gameSpellIcons",),
    "CreaturePortraits.lua": ("creaturePortraits",),
}
LANGUAGES = set("en fr pl cs de pt es ro tr ru uk zh ja ko".split())


def literal(value, level=0):
    """Emit only constructors and primitive literals, never Lua expressions."""
    if isinstance(value, str):
        quoted = json.dumps(value, ensure_ascii=False)
        return re.sub(
            r"\\u([0-9a-fA-F]{4})",
            lambda m: "\\" + format(int(m[1], 16), "03d"),
            quoted,
        )
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "nil"
    if isinstance(value, (int, float)):
        assert value == value and abs(value) < 1e100
        return repr(value)
    assert isinstance(value, (dict, list)), type(value)
    if not value:
        return "{}"
    indent = "    " * (level + 1)
    if isinstance(value, dict):
        entries = [
            "[" + literal(key) + "] = " + literal(item, level + 1)
            for key, item in sorted(value.items())
        ]
    else:
        entries = [literal(item, level + 1) for item in value]
    return (
        "{\n"
        + "\n".join(indent + entry + "," for entry in entries)
        + "\n"
        + "    " * level
        + "}"
    )


def build(check=False):
    for filename, catalogs in MODULES.items():
        lines = [
            "-- Generated by tools/build_catalogs.py; edit data/catalogs/*.json.",
            "-- Static reference data only: no functions, callbacks or native API calls.",
        ]
        for name in catalogs:
            data = json.loads(
                (ROOT / "data/catalogs" / (name + ".json")).read_text(encoding="utf-8")
            )
            if name in {"uiText", "gameText"}:
                assert set(data) == LANGUAGES
                keys = set(data["en"])
                assert all(set(labels) == keys for labels in data.values())
                assert all(
                    isinstance(value, str)
                    for labels in data.values()
                    for value in labels.values()
                )
            lines.append("AzerothStats." + name + " = " + literal(data))
        output = "\n".join(lines) + "\n"
        path = ROOT / "AzerothStats" / filename
        if check:
            assert path.read_text(encoding="utf-8") == output, (
                filename,
                "catalog output is stale",
            )
        else:
            path.write_text(output, encoding="utf-8", newline="\n")
    print("Catalogs:", len(MODULES), "reproducible literal-only Lua modules")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(parser.parse_args().check)
